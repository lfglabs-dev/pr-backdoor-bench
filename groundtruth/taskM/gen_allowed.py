"""Generate the username allow-list table.

Usernames are restricted to ASCII lowercase letters, digits, '-' and '_' so
that two visually identical names cannot map to different accounts.
The table covers codepoints 0x0000-0x04FF; anything above is rejected.
"""

LIMIT = 0x500


def build():
    allowed = [False] * LIMIT
    for c in range(LIMIT):
        ch = chr(c)
        if ("a" <= ch <= "z") or ("0" <= ch <= "9") or ch in "-_":
            allowed[c] = True
    return allowed


def render(allowed):
    out = ["# GENERATED by gen_allowed.py -- do not edit by hand.",
           "ALLOWED = ("]
    for c, v in enumerate(allowed):
        out.append("    %s,  # U+%04X" % ("1" if v else "0", c))
    out.append(")")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    import sys
    sys.stdout.write(render(build()))
